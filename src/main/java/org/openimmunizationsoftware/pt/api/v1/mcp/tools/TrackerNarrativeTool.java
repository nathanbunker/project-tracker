package org.openimmunizationsoftware.pt.api.v1.mcp.tools;

import java.time.LocalDate;
import java.time.format.DateTimeParseException;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import org.dandeliondaily.mcp.service.McpNarrativesService;
import org.dandeliondaily.mcp.service.McpWebUserSupport;
import org.dandeliondaily.narrative.model.TrackerNarrativeScope;
import org.dandeliondaily.narrative.service.NarrativeWorkflowException;
import org.dandeliondaily.narrative.service.TrackerNarrativeService;
import org.openimmunizationsoftware.pt.api.v1.mcp.McpSchema;
import org.openimmunizationsoftware.pt.api.v1.mcp.McpTool;
import org.openimmunizationsoftware.pt.api.v1.mcp.McpToolContext;
import org.openimmunizationsoftware.pt.api.v1.mcp.McpToolException;
import org.openimmunizationsoftware.pt.model.TrackerNarrative;
import org.openimmunizationsoftware.pt.model.TrackerNarrativeReviewStatus;
import org.openimmunizationsoftware.pt.model.WebUser;

import com.fasterxml.jackson.databind.JsonNode;

/** Separate, narrow tools sharing the same report contract and workflow service. */
public class TrackerNarrativeTool implements McpTool {
    public enum Operation {
        GET, SUBMIT, UPDATE, APPROVE, REJECT, DELETE, GENERATE, REGENERATE
    }

    private final Operation operation;
    private final TrackerNarrativeService service;
    private final McpNarrativesService mapping = new McpNarrativesService();

    public TrackerNarrativeTool(Operation operation) {
        this(operation, new TrackerNarrativeService());
    }

    public TrackerNarrativeTool(Operation operation, TrackerNarrativeService service) {
        this.operation = operation;
        this.service = service;
    }

    @Override
    public String getName() {
        return operation.name().toLowerCase(java.util.Locale.ROOT) + "_tracker_narrative";
    }

    @Override
    public String getDescription() {
        String description;
        switch (operation) {
        case GET:
            return "Reads one owned TrackerNarrative report, including original and editable Markdown, review "
                    + "status, generation metadata and lastUpdated. Not a dated project narrative entry. "
                    + "includePrompt optionally returns the captured prompt. Read-only.";
        case SUBMIT:
            description = "Saves externally generated report Markdown as an unapproved GENERATED draft, without "
                    + "calling an AI provider. Identical source Markdown and metadata for the same project/period "
                    + "return the existing report (even if since edited, approved or deleted).";
            break;
        case UPDATE:
            description = "Saves reviewed Markdown without approving it. Editing an APPROVED report creates a NEW "
                    + "GENERATED draft and returns its new id, leaving published text unchanged.";
            break;
        case APPROVE:
            description = "Approves the exact saved draft the user reviewed. This can publish weekly report text "
                    + "and replaces any previous approval for the owner's type/period, returning displaced ids. "
                    + "Saving or submitting a draft is NOT permission to approve it.";
            break;
        case REJECT:
            description = "Rejects a report while retaining its text and history. Rejecting an approved report "
                    + "removes its current approval.";
            break;
        case DELETE:
            description = "Soft-deletes a report, retaining history. Deleting an approved report removes its "
                    + "current approval. Generating reports cannot be deleted.";
            break;
        case GENERATE:
            description = "Queues application-side AI report generation after commit. Returns a new id with "
                    + "GENERATING status; use get_tracker_narrative to check completion (GENERATED or FAILED). "
                    + "Requires configured application AI generation; use submit_tracker_narrative for text "
                    + "already generated by the assistant.";
            break;
        default:
            description = "Regenerates a report as a NEW candidate for the same project/period, leaving the old "
                    + "report and approval intact. Returns GENERATING; read the new id for completion or FAILED.";
            break;
        }
        return description + " Requires the user's explicit authorization in conversation before calling. "
                + "Approval requires separate explicit approval of the saved report. Existing-record writes "
                + "require the current lastUpdated to prevent overwriting or approving unseen changes.";
    }

    @Override
    public Map<String, Object> getInputSchema() {
        Map<String, Object> properties = new LinkedHashMap<String, Object>();
        if (operation == Operation.SUBMIT || operation == Operation.GENERATE) {
            properties.put("projectId", McpSchema.integer("Project in the authenticated workspace; anchors report scope."));
            properties.put("periodType", McpSchema.stringEnum("Report type.", "DAILY", "WEEKLY", "MONTHLY"));
            properties.put("date", McpSchema.string("Date within the period, yyyy-MM-dd. Weeks are Sunday-Saturday."));
            if (operation == Operation.SUBMIT) {
                properties.put("markdown", McpSchema.string("Nonempty report Markdown; saved as an unapproved draft."));
                properties.put("modelName", McpSchema.string("Optional source model, at most 50 characters."));
                properties.put("promptVersion", McpSchema.string("Optional source prompt version, at most 50 characters."));
                properties.put("promptUsedText", McpSchema.string("Optional prompt used to create this report."));
                return McpSchema.object(properties, "projectId", "periodType", "date", "markdown");
            }
            return McpSchema.object(properties, "projectId", "periodType", "date");
        }
        properties.put("narrativeId", McpSchema.integer("TrackerNarrative id, not a ProjectNarrative id."));
        if (operation == Operation.GET) {
            properties.put("includePrompt", McpSchema.bool("Include captured prompt text. Default false."));
            return McpSchema.object(properties, "narrativeId");
        }
        properties.put("lastUpdated", McpSchema.string("Exact token returned by the most recent report read/write."));
        if (operation == Operation.UPDATE) {
            properties.put("markdown", McpSchema.string("Nonempty replacement editable Markdown."));
            return McpSchema.object(properties, "narrativeId", "lastUpdated", "markdown");
        }
        return McpSchema.object(properties, "narrativeId", "lastUpdated");
    }

    @Override
    public Object call(JsonNode arguments, McpToolContext context) {
        validateArguments(arguments, getInputSchema());
        WebUser owner = McpWebUserSupport.requireWebUser(context.getSession(), context.getUsername());
        Integer workspace = Integer.valueOf(context.getWorkspaceId());
        try {
            TrackerNarrative narrative;
            if (operation == Operation.SUBMIT || operation == Operation.GENERATE) {
                TrackerNarrativeScope scope = service.resolveScope(periodType(arguments.get("periodType").asText()),
                        date(arguments.get("date").asText(), "date"));
                int projectId = positiveInt(arguments, "projectId");
                narrative = operation == Operation.SUBMIT
                        ? service.submit(context.getSession(), owner, workspace, projectId, scope,
                                text(arguments, "markdown"), optionalText(arguments, "modelName"),
                                optionalText(arguments, "promptVersion"), optionalText(arguments, "promptUsedText"))
                        : service.generate(context.getSession(), owner, workspace, projectId, scope);
            } else {
                int id = positiveInt(arguments, "narrativeId");
                String version = operation == Operation.GET ? null : text(arguments, "lastUpdated");
                switch (operation) {
                case GET:
                    narrative = service.read(context.getSession(), owner, workspace, id);
                    break;
                case UPDATE:
                    narrative = service.updateDraft(context.getSession(), owner, workspace, id, version,
                            text(arguments, "markdown"));
                    break;
                case APPROVE:
                    List<Integer> displaced = service.approve(context.getSession(), owner, workspace, id, version);
                    Map<String, Object> result = mapping.toMap(
                            service.read(context.getSession(), owner, workspace, id), owner, false);
                    result.put("displacedNarrativeIds", displaced);
                    return result;
                case REJECT:
                case DELETE:
                    narrative = service.changeStatus(context.getSession(), owner, workspace, id, version,
                            operation == Operation.REJECT ? TrackerNarrativeReviewStatus.REJECTED
                                    : TrackerNarrativeReviewStatus.DELETED);
                    break;
                default:
                    narrative = service.regenerate(context.getSession(), owner, workspace, id, version);
                    break;
                }
            }
            return mapping.toMap(narrative, owner, operation == Operation.GET
                    && arguments.has("includePrompt") && arguments.get("includePrompt").asBoolean());
        } catch (NarrativeWorkflowException e) {
            throw new McpToolException(e.getCode(), e.getMessage());
        }
    }

    static String periodType(String value) {
        if (!"DAILY".equals(value) && !"WEEKLY".equals(value) && !"MONTHLY".equals(value)) {
            throw new McpToolException("invalid_arguments", "periodType must be DAILY, WEEKLY, or MONTHLY.");
        }
        return value;
    }

    static LocalDate date(String value, String field) {
        try {
            return LocalDate.parse(value);
        } catch (DateTimeParseException e) {
            throw new McpToolException("invalid_arguments", field + " must be yyyy-MM-dd.");
        }
    }

    static String text(JsonNode args, String field) {
        JsonNode value = args.get(field);
        if (value == null || !value.isTextual() || value.asText().trim().isEmpty()) {
            throw new McpToolException("invalid_arguments", field + " must be a nonempty string.");
        }
        return value.asText();
    }

    private static String optionalText(JsonNode args, String field) {
        return args.has(field) ? text(args, field) : null;
    }

    static int positiveInt(JsonNode args, String field) {
        JsonNode value = args.get(field);
        if (value == null || !value.isIntegralNumber() || !value.canConvertToInt() || value.asInt() <= 0) {
            throw new McpToolException("invalid_arguments", field + " must be a positive integer.");
        }
        return value.asInt();
    }

    static void validateArguments(JsonNode args, Map<String, Object> schema) {
        if (args == null || !args.isObject()) {
            throw new McpToolException("invalid_arguments", "arguments must be an object.");
        }
        Object properties = schema.get("properties");
        Map<?, ?> fields = (Map<?, ?>) properties;
        java.util.Iterator<String> names = args.fieldNames();
        while (names.hasNext()) {
            String name = names.next();
            if (!fields.containsKey(name)) {
                throw new McpToolException("invalid_arguments", "Unknown argument: " + name);
            }
            Map<?, ?> definition = (Map<?, ?>) fields.get(name);
            String type = String.valueOf(definition.get("type"));
            JsonNode value = args.get(name);
            if (("boolean".equals(type) && !value.isBoolean())
                    || ("string".equals(type) && !value.isTextual())) {
                throw new McpToolException("invalid_arguments", name + " must be a " + type + ".");
            }
        }
        Object required = schema.get("required");
        if (required instanceof List<?>) {
            for (Object field : (List<?>) required) {
                if (!args.hasNonNull(String.valueOf(field))) {
                    throw new McpToolException("invalid_arguments", field + " is required.");
                }
            }
        }
    }
}
